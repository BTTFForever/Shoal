#!/usr/bin/env python3
"""Embeds ShoalCore/shaders into a C++ source file: `const char* ShoalShaderSource(const char* name)`.

Usage: embed_shaders.py <shader dir> <out.cpp>. Every host build (ShoalLinux, ShoalWallpaper, ShoalWindows) runs this,
so the shaders in ShoalCore/shaders are the only copy.
"""
import pathlib
import sys

src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
lines = ["// Generated by ShoalCore/embed_shaders.py from ShoalCore/shaders. Do not edit.", "#include <cstring>", "",
         "const char* ShoalShaderSource(const char* name)", "{"]
for f in sorted(src.iterdir()):
    if f.suffix not in (".comp", ".vert", ".frag"):
        continue
    # Raw string literals with a delimiter that can't appear in GLSL, split at line ends into pieces under 4 KB:
    # MSVC rejects single literals over 16 KB (sim.comp is bigger), and adjacent literals are joined anyway.
    pieces, piece = [], ""
    for line in f.read_text().splitlines(keepends=True):
        if piece and len(piece) + len(line) > 4000:
            pieces.append(piece)
            piece = ""
        piece += line
    pieces.append(piece)
    literal = "\n        ".join(f'R"SHOAL({p})SHOAL"' for p in pieces)
    lines.append(f'    if (std::strcmp(name, "{f.name}") == 0)\n        return {literal};')
lines += ["    return nullptr;", "}", ""]
text = "\n".join(lines)
if not out.exists() or out.read_text() != text:  # keep the timestamp when nothing changed
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
